def sanitize_snippet(snippet: str) -> str:
    """
    Sanitize HTML snippet to only allow <mark> tags for highlighting.

    This prevents XSS by stripping all HTML except the highlighting markers
    generated by SQLite's FTS5 highlight() function.

    Args:
        snippet: Raw snippet text with potential HTML

    Returns:
        Sanitized snippet with only <mark> and </mark> tags allowed
    """
    # First escape all HTML entities
    import html
    snippet = html.escape(snippet)

    # Then un-escape only the mark tags
    snippet = snippet.replace("&lt;mark&gt;", "<mark>")
    snippet = snippet.replace("&lt;/mark&gt;", "</mark>")

    return snippet


def save_resolution(session: Session, parse_result: ParseResult, full_text: str) -> Resolution:
    """
    Save a parsed resolution to the database.

    Args:
        session: Database session
        parse_result: ParseResult from Phase 1 parser
        full_text: Complete OCR text for FTS indexing

    Returns:
        Created Resolution with id populated
    """
    # Create Resolution
    resolution = Resolution(
        document_id=parse_result.document_id,
        resolution_number=parse_result.resolution_number,
        title=None,  # Can be extracted from first line or summary
        date_adopted=parse_result.date_adopted,
        convention_name=parse_result.convention.get("name") if parse_result.convention else None,
        convention_location=parse_result.convention.get("location") if parse_result.convention else None,
        convention_year=parse_result.convention.get("year") if parse_result.convention else None,
        full_text=full_text,
        parse_confidence=parse_result.confidence_score,
        needs_review=parse_result.needs_review,
    )
    session.add(resolution)
    session.flush()  # Get resolution.id

    # Create Statements
    for stmt in parse_result.whereas_statements:
        statement = Statement(
            resolution_id=resolution.id,
            statement_type="whereas",
            index=stmt.get("index", 0),
            text=stmt.get("text", ""),
            function=stmt.get("function"),
        )
        session.add(statement)

    for stmt in parse_result.resolved_statements:
        statement = Statement(
            resolution_id=resolution.id,
            statement_type="resolved",
            index=stmt.get("index", 0),
            text=stmt.get("text", ""),
            action_type=stmt.get("action_type"),
        )
        session.add(statement)

    # Create Citations
    for cite in parse_result.citations:
        citation = Citation(
            resolution_id=resolution.id,
            text=cite.get("text", ""),
            normalized=cite.get("normalized", ""),
            citation_type=cite.get("type", "other"),
        )
        session.add(citation)

    # Create Sponsors
    sponsors = parse_result.sponsors
    for name in sponsors.get("primary", []):
        sponsor = Sponsor(resolution_id=resolution.id, name=name, sponsor_type="primary")
        session.add(sponsor)

    for name in sponsors.get("co_sponsor", []):
        sponsor = Sponsor(resolution_id=resolution.id, name=name, sponsor_type="co_sponsor")
        session.add(sponsor)

    if sponsors.get("committee"):
        sponsor = Sponsor(resolution_id=resolution.id, name=sponsors["committee"], sponsor_type="committee")
        session.add(sponsor)

    session.commit()
    session.refresh(resolution)
    return resolution


def get_resolution(session: Session, resolution_id: int) -> Optional[Resolution]:
    """Get resolution by ID with all relationships loaded."""
    return session.get(Resolution, resolution_id)


def get_resolution_by_document_id(session: Session, document_id: str) -> Optional[Resolution]:
    """Get resolution by document_id."""
    return session.exec(select(Resolution).where(Resolution.document_id == document_id)).first()


def list_resolutions(session: Session, limit: int = 100, offset: int = 0) -> List[Resolution]:
    """List resolutions with pagination."""
    return list(session.exec(select(Resolution).offset(offset).limit(limit)))


def search_resolutions(
    session: Session,
    query: str,
    limit: int = 20,
    year: Optional[int] = None,
    sponsor: Optional[str] = None,
) -> List[Dict[str, Any]]:
    """
    Full-text search with relevance ranking and snippet highlighting.

    Args:
        session: Database session
        query: Search query (FTS5 MATCH syntax)
        limit: Maximum results
        year: Optional filter by convention year
        sponsor: Optional filter by sponsor name

    Returns:
        List of dicts with id, resolution_number, title, snippet, score
    """
    engine = get_engine()

    # Base FTS5 search query with bm25 ranking
    sql = """
        SELECT
            r.id,
            r.document_id,
            r.resolution_number,
            r.title,
            r.date_adopted,
            r.convention_year,
            highlight(resolution_fts, 2, '<mark>', '</mark>') as snippet,
            bm25(resolution_fts) as score
        FROM resolution_fts
        JOIN resolution r ON r.id = resolution_fts.rowid
        WHERE resolution_fts MATCH :query
    """
    params: Dict[str, Any] = {"query": query, "limit": limit}

    # Optional filters
    if year:
        sql += " AND r.convention_year = :year"
        params["year"] = year

    if sponsor:
        sql += """ AND r.id IN (
            SELECT resolution_id FROM sponsor WHERE name LIKE :sponsor
        )"""
        params["sponsor"] = f"%{sponsor}%"

    sql += " ORDER BY score LIMIT :limit"

    with engine.connect() as conn:
        result = conn.execute(text(sql), params)
        rows = result.fetchall()

    return [
        {
            "id": row[0],
            "document_id": row[1],
            "resolution_number": row[2],
            "title": row[3],
            "date_adopted": str(row[4]) if row[4] else None,
            "convention_year": row[5],
            "snippet": sanitize_snippet(row[6]) if row[6] else "",
            "score": row[7],
        }
        for row in rows
    ]


def get_all_themes(session: Session) -> List[Dict[str, Any]]:
    """
    Get all themes with resolution counts.

    Returns:
        List of dicts with id, name, description, icon, resolution_count
    """
    engine = get_engine()

    sql = """
        SELECT t.id, t.name, t.description, t.icon,
               COUNT(rt.resolution_id) as resolution_count
        FROM theme t
        LEFT JOIN resolutiontheme rt ON rt.theme_id = t.id
        GROUP BY t.id, t.name, t.description, t.icon
        ORDER BY t.name
    """

    with engine.connect() as conn:
        result = conn.execute(text(sql))
        rows = result.fetchall()

    return [
        {
            "id": row[0],
            "name": row[1],
            "description": row[2],
            "icon": row[3],
            "resolution_count": row[4],
        }
        for row in rows
    ]


def get_resolutions_by_theme(session: Session, theme_id: int) -> List[Resolution]:
    """
    Get all resolutions for a theme.

    Args:
        session: Database session
        theme_id: Theme ID

    Returns:
        List of Resolution objects
    """
    resolution_ids = session.exec(
        select(ResolutionTheme.resolution_id).where(ResolutionTheme.theme_id == theme_id)
    ).all()

    if not resolution_ids:
        return []

    return list(session.exec(
        select(Resolution)
        .where(Resolution.id.in_(resolution_ids))
        .order_by(Resolution.convention_year.desc())
    ))


def get_themes_for_resolution(session: Session, resolution_id: int) -> List[Theme]:
    """
    Get themes assigned to a resolution.

    Args:
        session: Database session
        resolution_id: Resolution ID

    Returns:
        List of Theme objects
    """
    theme_ids = session.exec(
        select(ResolutionTheme.theme_id).where(ResolutionTheme.resolution_id == resolution_id)
    ).all()

    if not theme_ids:
        return []

    return list(session.exec(
        select(Theme).where(Theme.id.in_(theme_ids)).order_by(Theme.name)
    ))


def get_theme_by_id(session: Session, theme_id: int) -> Optional[Theme]:
    """Get a theme by ID."""
    return session.get(Theme, theme_id)
